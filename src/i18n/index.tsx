const DICTS: Record<Lang, Dict> = { 'zh-TW': zh, en }

export type TFunc = (key: string, vars?: Record<string, string | number>) => string

interface I18n {
  lang: Lang
  setLang: (l: Lang) => void
  t: TFunc
  locale: string
}

const Ctx = createContext<I18n | null>(null)

function readStored(): Lang {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    if (v === 'zh-TW' || v === 'en') return v
  } catch {
    /* storage unavailable */
  }
  return 'zh-TW'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readStored)

  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem(STORAGE_KEY, l)
    } catch {
      /* ignore */
    }
  }, [])

  const t = useCallback<TFunc>(
    (key, vars) => {
      let s = DICTS[lang][key] ?? DICTS['en'][key] ?? key
      if (vars) for (const k of Object.keys(vars)) s = s.replace(`{${k}}`, String(vars[k]))
      return s
    },
    [lang],
  )

  const value = useMemo<I18n>(
    () => ({ lang, setLang, t, locale: lang === 'zh-TW' ? 'zh-TW' : 'en-US' }),
    [lang, setLang, t],
  )

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n must be used within I18nProvider')
  return v
}

/** Localized date formatting that follows the active language. */
export function fmtDate(iso: string, locale: string, opts: Intl.DateTimeFormatOptions): string {
  return new Date(iso + 'T00:00:00Z').toLocaleDateString(locale, { ...opts, timeZone: 'UTC' })
}
